#!/usr/bin/env python3
"""Bundle Facts into the existing Reduction Pages project's public output."""
import argparse
import json
import runpy
import shutil
from pathlib import Path
from urllib.parse import urlsplit

MARKER = "// Reduction Facts Pages router — generated by pipeline/build_site.py\n"
ROUTES = {"version": 1, "include": ["/*"], "exclude": []}

def build(root):
    public = root / "public"
    facts = root / "facts"
    if not (public / "index.html").is_file():
        raise RuntimeError("Main homepage missing: expected public/index.html")
    for name in ["index.html", "styles.css", "engine.js", "app.js", "facts.json", "themes.json"]:
        if not (facts / name).is_file():
            raise RuntimeError(f"Missing Facts source file: facts/{name}")
    functions = root / "functions"
    if functions.exists() and any(p.is_file() for p in functions.rglob("*")):
        raise RuntimeError("Existing Pages Functions detected. Stop: merge routing with those Functions rather than replacing them.")
    router = public / "_worker.js"
    if router.exists() and not router.read_text(encoding="utf-8").startswith(MARKER):
        raise RuntimeError("Existing custom _worker.js detected. Stop for a routing review.")
    route_file = public / "_routes.json"
    if route_file.exists() and json.loads(route_file.read_text()) != ROUTES:
        raise RuntimeError("Existing custom _routes.json detected. Stop for a routing review.")
    redirects = public / "_redirects"
    if redirects.exists():
        active = [line.strip() for line in redirects.read_text().splitlines() if line.strip() and not line.lstrip().startswith("#")]
        if any(line.split() != ["/rtx/", "/rtx", "301"] for line in active):
            raise RuntimeError("Additional _redirects rules detected. Add equivalent behavior to the router before deploying.")
    data = json.loads((facts / "facts.json").read_text(encoding="utf-8"))
    entries = data["statistics"]
    sources = {s["source_id"]: s for s in data["sources"]}
    if len({f["id"] for f in entries}) != len(entries):
        raise RuntimeError("Duplicate fact IDs")
    expected = data.get("metadata", {}).get("entry_count")
    if expected is not None and expected != len(entries):
        raise RuntimeError("Dataset metadata count does not match actual entries")
    for f in entries:
        if not f.get("statement") or not f.get("source_ids"):
            raise RuntimeError(f"Fact missing statement or sources: {f.get('id')}")
        for sid in f["source_ids"]:
            if sid not in sources or urlsplit(sources[sid]["url"]).scheme not in {"http", "https"}:
                raise RuntimeError(f"Unresolved or unsafe source: {sid}")
    # This is a generated output folder only. Source data stays untouched in root/facts/.
    destination = public / "facts"
    if destination.exists():
        shutil.rmtree(destination)
    # Discover public pages BEFORE copying generated Facts HTML into public/facts.
    nav_scope = runpy.run_path(str(root / "pipeline" / "build_site_navigation.py"))
    nav = nav_scope["build"](root)
    shutil.copytree(facts, destination, ignore=shutil.ignore_patterns(".DS_Store", "_headers", "_redirects", "_worker.js", "_routes.json", "__pycache__"))
    paths = sorted("/" + p.relative_to(destination).as_posix() for p in destination.rglob("*") if p.is_file())
    paths = sorted(set(paths + ["/"]))
    template = (root / "routing" / "facts-worker.js").read_text(encoding="utf-8")
    if template.count("__FACT_PATHS__") != 1:
        raise RuntimeError("Router asset-list placeholder missing or duplicated")
    router.write_text(MARKER + template.replace("__FACT_PATHS__", json.dumps(paths)), encoding="utf-8")
    route_file.write_text(json.dumps(ROUTES, indent=2) + "\n", encoding="utf-8")
    eligible = sum(f.get("review_status") not in {"needs_review", "rejected", "withdrawn"} for f in entries)
    print(f"Built navigation: {len(nav['items'])} pages")
    print(f"Facts: {len(entries)} records, {eligible} in rotation, {len(sources)} sources")
    print("Published output: public (main site + Facts + hostname router)")
    return {"entries": len(entries), "eligible": eligible, "paths": paths}

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    build(args.root.resolve())
